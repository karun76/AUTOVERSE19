export type CompactCarTuple = [
  brand: string,
  model: string,
  year: number,
  type: string,
  hp: number,
  torque: number,
  top: number,
  acc: string,
  engine: string,
  fuel: string,
  price: string,
  image: string,
  description?: string,
];

export function expandTuples(tuples: CompactCarTuple[]) {
  return tuples.map(
    ([
      brand,
      model,
      year,
      type,
      hp,
      torque,
      top,
      acc,
      engine,
      fuel,
      price,
      image,
      description,
    ]) => ({
      brand,
      model,
      year,
      type,
      hp,
      torque,
      top,
      acc,
      engine,
      fuel,
      price,
      image,
      description:
        description ??
        `The ${year} ${brand} ${model} pairs ${engine} engineering delivering ${hp} HP with refined ${type.toLowerCase()} dynamics.`,
    }),
  );
}
